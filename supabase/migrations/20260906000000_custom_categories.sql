-- =====================================================================

-- 1. เพิ่มคอลัมน์ category_type เพื่อระบุว่าหมวดหมู่นั้นเป็น "หลัก" หรือ "แฝง"
--    เดิม UI (js/dashboard.js, js/history.js) ตัดสินด้วยการเช็ค category_id
--    แบบ hardcode ว่าอยู่ใน [4,5,6] หรือไม่ ซึ่งใช้กับหมวดหมู่ใหม่ที่ผู้ใช้สร้างเองไม่ได้
--    (id จะไม่ตรงกับ [4,5,6] แน่นอน) จึงต้องย้าย field นี้มาเก็บในตารางแทน
ALTER TABLE categories
    ADD COLUMN category_type VARCHAR(10) NOT NULL DEFAULT 'หลัก'
    CONSTRAINT chk_categories_type CHECK (category_type IN ('หลัก', 'แฝง'));

-- 2. Backfill หมวดหมู่ seed เดิม: อาหาร/วัคซีน/ถ่ายพยาธิ = หลัก (ค่า default อยู่แล้ว)
--    ค่าใช้จ่ายแฝง 3 หมวดที่เหลือ = แฝง
UPDATE categories SET category_type = 'แฝง'
WHERE category_name IN (
    'ค่าใช้จ่ายแฝง - ค่ารักษาพยาบาลฉุกเฉิน',
    'ค่าใช้จ่ายแฝง - สิ่งของเสียหาย',
    'ค่าฝากเลี้ยง'
);

-- 3. เพิ่ม INSERT policy ให้ผู้ใช้ที่ล็อกอินแล้วสร้างหมวดหมู่ใหม่ได้
--    (ก่อนหน้านี้มีแค่ categories_select — ไม่มี INSERT policy เลย ทำให้ยังไม่มีใคร
--    เพิ่มหมวดหมู่เองได้แม้แต่คนเดียว เพราะ RLS ปิดกั้นโดย default)
--    หมวดหมู่เป็นข้อมูลกลางที่ทุกคนอ่านได้อยู่แล้ว (categories_select: USING (true))
--    จึงให้สร้างได้แบบเดียวกัน ไม่ผูกกับ Owner/Co-caretaker ของสัตว์เลี้ยงตัวใดตัวหนึ่ง
DROP POLICY IF EXISTS "categories_insert" ON categories;
CREATE POLICY "categories_insert" ON categories FOR INSERT WITH CHECK (
    auth.uid() IS NOT NULL
);
