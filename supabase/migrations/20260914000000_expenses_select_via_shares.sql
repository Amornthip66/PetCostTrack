DROP POLICY IF EXISTS "expenses_select" ON public.expenses;
CREATE POLICY "expenses_select" ON public.expenses
    FOR SELECT USING (
        user_has_pet_access(pet_id)
        OR EXISTS (
            SELECT 1 FROM expense_pet_shares eps
            WHERE eps.transaction_id = expenses.transaction_id
            AND user_has_pet_access(eps.pet_id)
        )
    );
